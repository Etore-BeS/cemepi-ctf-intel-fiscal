def schema_sql() -> str:
    tables = ", ".join(f"'{name}'" for name in SCHEMA_TABLES)
    sql = f"""
        SELECT table_name, column_name, data_type
        FROM information_schema.columns
        WHERE table_schema = 'src'
          AND table_name IN ({tables})
        ORDER BY table_name, ordinal_position
    """
    assert_safe_sql(sql)
    return sql


